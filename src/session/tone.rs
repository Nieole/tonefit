//! **语义色**：屏上把「这件事怎么样」分成的**四种**（`CONTEXT.md` 的《会话》：语义色）。
//!
//! 本模块只有那一个枚举。它答的是**语义**——这一行是隔离、是跳过、是没做成——
//! 不是颜色：四种在屏上各是什么样、上不上色，都在画法那一层的 `super::draw::paint`
//! 一处定（本仓库唯一写得出颜色名的地方），本模块一个 `Color::` 都不写。
//!
//! # 它一个终端都不碰
//!
//! 因此摆在 `tui` 特性**外面**（见 `super` 的《终端库在哪一半》），与
//! [`Viewport`](super::viewport::Viewport)、[`columns`](super::columns) 同一侧。
//! 要它在这一侧的是**状态机**：屏底那一句由 [`super::state`] 说出口，而说出口的那一刻
//! 就定了它有多重（一条拒绝是出事、「再按一次」是注意、「存好了」是平常）。
//! 从前它住在画法那一层、这一侧够不着，屏底那一句只好自己另挂一个三档的类型，
//! 再由画法折成语义色——「这一句有多重」于是有两个类型说得出
//! （`no-false-line/05`，收停车场 Q198）。
//!
//! **自己一个模块，不并进 [`super::state`]**：它不是状态——状态机只是说得出它的那一头，
//! 画法那六块个个要它；`CONTEXT.md` 把《语义色》当《会话》一节自己的一个词，
//! 与《视口》《砍列》同级，那两个各有各的模块。另一条路与代价在停车场 Q657。
//!
//! # 它不带记号
//!
//! **没有一个「这一档配哪个记号」的方法。**《语义色》那句「颜色不是唯一载体——
//! 每一处上色的地方旁边都另有一个字或一个行首记号」是**对每一处的要求**，不是这个类型的
//! 一个属性：语义色是**多对一**的（「注意」一档在 `CONTEXT.md` 的《语义色》里列着八样，
//! 卷级的隔离、页级的特例页、屏底那一句问的「再按一次」都在里面），
//! 一个方法答不出那几样各配什么记号。
//! 卷表那四对四（`super::draw::table` 的记号到语义色）是**巧合**，不是构造，
//! 而且**方向只有一个**：记号定语义，语义不反推记号。
//!
//! 那句话落成的是**一条闸门**，在画法那一层（`super::draw::paint` 的
//! `every_painted_block_carries_a_word_or_a_mark_of_its_own`）：走一遍屏，
//! 凡是上了色的地方都得配着一个字或一个行首记号。

/// **四种语义**，屏上一种一个样子（四种各是什么样见 `super::draw::paint` 那张表）。
///
/// 画法各处要的是这四个字之一，不是颜色：颜色名只在 `super::draw::paint::style` 里出现。
///
/// **四种有轻重**，按 [`Ord`] 从轻到重排：不要紧 < 平常 < 注意 < 出事。
/// 派生它是为了一件具体的事——**一行上摆着好几件事时取最重的那一种**
/// （总览块的出事行同时数着隔离与失败页，见 `super::draw::overview`）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Tone {
    /// **不要紧**：跳过的卷、只读时的左栏。屏上压暗。
    Muted,
    /// **平常**：正常跑完的卷、普通的页、非卷文件那一小结、屏底那一句报的「做成了」。
    /// 屏上是终端默认色。
    Plain,
    /// **注意**：隔离、部分救回、宽溢出、兜底上界、几何门不成立、特例页、过期副本，
    /// 以及屏底那一句问的「再按一次」。屏上黄。
    Caution,
    /// **出事**：失败页、卷级失败、拒绝执行，以及屏底那一句报的「没做成」。屏上红。
    Trouble,
}

#[cfg(test)]
mod tests {
    use super::Tone;

    /// **四种语义有轻重，一行上摆着好几件事时取最重的那一种。**
    ///
    /// 总览块的出事行同时数着隔离（注意）与失败页（出事），而它只有一种颜色
    /// （见 `super::super::draw::overview`）。这一条在 `tui` 特性外面跑：轻重是语义的事，
    /// 不是颜色的事。
    #[test]
    fn the_four_tones_run_from_the_least_to_the_most_serious() {
        assert!(Tone::Muted < Tone::Plain);
        assert!(Tone::Plain < Tone::Caution);
        assert!(Tone::Caution < Tone::Trouble);
        assert_eq!(
            [Tone::Caution, Tone::Trouble, Tone::Plain]
                .into_iter()
                .max(),
            Some(Tone::Trouble)
        );
    }
}
